"""Writes docs/report/tests.md from the test runners' own reports, so the list
is the suite that ran, not one typed by hand.

  (cd app && flutter test --reporter json) > app.json
  (cd backend && go test -json ./...) > go.json
  python3 docs/report/test_list.py app.json go.json > docs/report/tests.md
"""

import collections
import datetime
import glob
import json
import re
import subprocess
import sys

AREAS = [
    ('domain', 'Domain: pure business logic, no Flutter, no I/O'),
    ('application', 'Application: providers and notifiers, on fakes'),
    ('data', 'Data: repositories, DAOs, codecs, on an in-memory database and fake servers'),
    ('drift', 'Data: schema migrations, every version to the next'),
    ('presentation', 'Presentation: widgets, screens, accessibility'),
    ('core', 'Core: money, formats, localisation, theme'),
    ('app', 'Whole app: boot, layer rules, the offline walk'),
]

# The edge cases CLAUDE.md asks every domain function to cover, and words
# their tests use.
EDGE_CASES = [
    ('Empty history or no data', r'\bempty\b|\bno (data|history|bars?|closes?|prices?|values?)\b|nothing'),
    ('A single data point', r'\bsingle\b|\bone (bar|point|close|day|value)\b|\bonly one\b'),
    ('Zero or negative amount', r'\bzero\b|\bnegative\b|\b0 ?(€|%)'),
    ('Missing price for a date', r'\bmissing\b|\bwithout (a |any )?(price|bar|quote|rate|close)\b|day without|\bno (quote|price|close|bar) (for|on|at)\b'),
    ('Weekend or holiday', r'weekend|holiday|saturday|sunday|closed'),
    ('Dates outside the data range', r'before (the )?(first (bar|day|date|close|trading)|listing|data floor)|\bafter (the )?last\b|past the (last|end|data|cache)|out of range|beyond|\bfloor\b|lookahead|after asOf'),
    ('Division by zero', r'division|by zero|undefined'),
    ('Currency mismatch or conversion', r'currenc|\bfx\b|exchange rate|mismatch|dollar|\busd\b|\beur\b'),
]


def flutter(path):
    suites, starts, done = {}, {}, []
    for line in open(path, encoding='utf-8'):
        if not line.startswith('{'):
            continue
        event = json.loads(line)
        kind = event.get('type')
        if kind == 'suite':
            suites[event['suite']['id']] = event['suite']['path']
        elif kind == 'testStart':
            starts[event['test']['id']] = event['test']
        elif kind == 'testDone' and not event['hidden']:
            test = starts[event['testID']]
            file = re.sub(r'^.*/app/', '', suites[test['suiteID']])
            done.append((file, test['name'], event['result']))
    return done


def area(file):
    parts = file.split('/')
    return parts[1] if len(parts) > 2 else 'app'


def go(path):
    tests = []
    for line in open(path, encoding='utf-8'):
        event = json.loads(line)
        if event.get('Test') and event['Action'] in ('pass', 'fail', 'skip'):
            package = event['Package'].removeprefix('finance-companion/backend/')
            tests.append((package, event['Test'], event['Action']))
    return tests


def main(app_json, go_json):
    app = flutter(app_json)
    backend = go(go_json)
    commit = subprocess.run(
        ['git', 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True
    ).stdout.strip()
    failed = [t for t in app if t[2] != 'success'] + [t for t in backend if t[2] != 'pass']
    out = []
    w = out.append
    w('# Tests')
    w('')
    w(f'Generated by `docs/report/test_list.py` from the runners\' own reports on '
      f'{datetime.date.today().isoformat()}, commit `{commit}`: the suite that ran, '
      f'{"all passing" if not failed else f"{len(failed)} FAILING"}. '
      'CI runs both on every pull request (`.github/workflows/ci.yml`), after `flutter analyze` and '
      '`go vet`.')
    w('')
    w('## Summary')
    w('')
    w('| Area | Files | Tests |')
    w('|---|---:|---:|')
    by_area = collections.defaultdict(list)
    for file, name, result in app:
        by_area[area(file)].append((file, name))
    for key, label in AREAS:
        tests = by_area.get(key, [])
        w(f'| {label} | {len({f for f, _ in tests})} | {len(tests)} |')
    w(f'| **App total** | **{len({f for f, _, _ in app})}** | **{len(app)}** |')
    top = [t for t in backend if '/' not in t[1]]
    cases = f' ({len(backend)} with subtests)' if len(backend) != len(top) else ''
    w(f'| Backend (Go): handlers, store, sync jobs, provider adapter, content checks | '
      f'{len({p for p, _, _ in top})} packages | {len(top)}{cases} |')
    w('')
    shots = len(glob.glob('docs/screenshots/*.png'))
    w(f'Not counted above: {shots} screenshot tests (`app/screenshots/`, rendered to `docs/screenshots/`, '
      'run by hand), the provider adapter against the real API (`go test -tags live`), the content check '
      'of every lesson pack (`cmd/contentcheck`, in CI), and the manual offline script (`docs/qa/offline.md`).')
    w('')
    w('## Edge cases')
    w('')
    w('Tests whose name names the case, with a few examples. A test can cover a case without naming it.')
    w('')
    w('| Case | Tests | Examples |')
    w('|---|---:|---|')
    for label, pattern in EDGE_CASES:
        rx = re.compile(pattern, re.IGNORECASE)
        hits = [(f, n) for f, n, _ in app if rx.search(n)]
        domain_first = sorted(hits, key=lambda t: area(t[0]) != 'domain')
        examples = '; '.join(
            f'« {n} » (`{f.removeprefix("test/")}`)' for f, n in domain_first[:3]
        )
        w(f'| {label} | {len(hits)} | {examples} |')
    w('')
    w('## Every test')
    for key, label in AREAS:
        tests = by_area.get(key, [])
        if not tests:
            continue
        w('')
        w(f'<details><summary><b>{label}</b> ({len(tests)})</summary>')
        w('')
        by_file = collections.defaultdict(list)
        for file, name in tests:
            by_file[file].append(name)
        for file in sorted(by_file):
            w(f'**`{file}`**')
            w('')
            for name in by_file[file]:
                w(f'- {name}')
            w('')
        w('</details>')
    w('')
    w(f'<details><summary><b>Backend (Go)</b> ({len(top)})</summary>')
    w('')
    by_package = collections.defaultdict(list)
    for package, name, _ in top:
        by_package[package].append(name)
    for package in sorted(by_package):
        w(f'**`backend/{package}`**')
        w('')
        for name in by_package[package]:
            subtests = sum(1 for p, n, _ in backend if p == package and n.startswith(name + '/'))
            w(f'- {name}' + (f' ({subtests} cases)' if subtests else ''))
        w('')
    w('</details>')
    print('\n'.join(out))


if __name__ == '__main__':
    main(*sys.argv[1:3])
